# Strings - Working with Textual Data
message = "Hello Abhinav"

# Printing String Variables 
print(message)

# Length of the String
print(len(message))

# Accessing String using Indexes (Positive Indexing or Zero Based Indexing)
print(message[1])

# Accessing String using Indexes (Negative Indexing)
print(message[-2])

# Accessing String using Range of Indexes
print(message[0:5])
print(message[:5])
print(message[6:])